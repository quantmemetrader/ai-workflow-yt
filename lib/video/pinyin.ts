let byChar: Map<string, string[]> | null = null;

/** Every reading of `ch` in the table, most common first; empty for a character it does not know. */
export function readingsOf(ch: string): readonly string[] {
  if (!byChar) {
    byChar = new Map();
    for (const entry of TABLE) {
      const syllable = /^[a-z]+/.exec(entry)![0];
      for (const c of Array.from(entry.slice(syllable.length))) {
        const had = byChar.get(c);
        if (had) had.push(syllable);
        else byChar.set(c, [syllable]);
      }
    }
  }
  return byChar.get(ch) ?? [];
}

const INITIALS = /^(zh|ch|sh|[bpmfdtnlgkhjqxrzcsyw])?(.*)$/;

/**
 * A syllable with the confusions Mandarin speech recognition (and many
 * speakers) make folded away: retroflex and flat initials (zh/z, ch/c,
 * sh/s) and front and back nasals (ing/in, eng/en, ang/an). 帧 zhen and
 * 蒸 zheng fold to the same "zen".
 */
export function foldSyllable(s: string): string {
  return s
    .replace(/^zh/, "z")
    .replace(/^ch/, "c")
    .replace(/^sh/, "s")
    .replace(/ing$/, "in")
    .replace(/eng$/, "en")
    .replace(/ang$/, "an");
}

/** Edit distance between two short ASCII strings. */
function distance(a: string, b: string): number {
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    prev = cur;
  }
  return prev[b.length];
}

/**
 * How two characters compare by sound: "same" when they are the same
 * character or share a reading after folding; "near" when some pair of
 * readings has the same initial and finals at most two letters apart
 * (西 xi / 谢 xie, 裂 lie / 链 lian); null otherwise.
 */
export function charSound(a: string, b: string): "same" | "near" | null {
  if (a === b) return "same";
  const ra = readingsOf(a).map(foldSyllable);
  const rb = readingsOf(b).map(foldSyllable);
  if (!ra.length || !rb.length) return null;
  if (ra.some((x) => rb.includes(x))) return "same";
  for (const x of ra) {
    for (const y of rb) {
      const [, ix = "", fx] = INITIALS.exec(x)!;
      const [, iy = "", fy] = INITIALS.exec(y)!;
      if (ix === iy && distance(fx, fy) <= 2) return "near";
    }
  }
  return null;
}

/**
 * Whether `heard` is plausibly `meant` misheard, character for character.
 * Same length, every character known to the table, and every position
 * the same sound after folding, except that a word of three or more
 * characters may have one position that is only near (西雅芳 → 谢亚芳,
 * 丝为裂 → 思维链) unless `near: false` asks for exact homophones only.
 * Two-character words get no leeway: one near syllable out of two turns
 * 正路 into 蒸馏. Returns the positions where the characters differ, for
 * the caller's own checks, or null when they do not sound alike (or are
 * identical).
 */
export function soundsAlike(heard: string, meant: string, options: { near?: boolean } = {}): number[] | null {
  const h = Array.from(heard);
  const m = Array.from(meant);
  if (h.length !== m.length || h.length < 2) return null;
  const differ: number[] = [];
  let near = 0;
  for (let k = 0; k < h.length; k++) {
    if (h[k] === m[k]) continue;
    const s = charSound(h[k], m[k]);
    if (!s) return null;
    if (s === "near") near++;
    differ.push(k);
  }
  if (!differ.length) return null;
  if (near > (h.length >= 3 && options.near !== false ? 1 : 0)) return null;
  return differ;
}
